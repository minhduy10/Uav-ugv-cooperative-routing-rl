class ScalableTransformerPolicy(TransformerPolicy):
    """
    Backward-compatible name used by the original training code.

    The architecture itself is identical to TransformerPolicy.
    Larger model capacity is selected through constructor arguments.

    Example
    -------
    Small / Medium:

        ScalableTransformerPolicy(
            embed_dim=192,
            nhead=6,
            num_layers=3,
        )

    Large:

        ScalableTransformerPolicy(
            embed_dim=256,
            nhead=8,
            num_layers=4,
        )
    """

    pass


# ============================================================
# Factory function
# ============================================================


def build_policy(
    *,
    is_large: bool = False,
    in_nodes: int = NODE_FEATURE_DIM,
    dropout: float = 0.1,
) -> TransformerPolicy:
    """
    Build a policy using the model sizes from the experiments.

    Small / Medium
    --------------
    embed_dim = 192
    nhead = 6
    num_layers = 3

    Large
    -----
    embed_dim = 256
    nhead = 8
    num_layers = 4
    """

    if is_large:

        return ScalableTransformerPolicy(
            in_nodes=in_nodes,
            embed_dim=256,
            nhead=8,
            num_layers=4,
            dropout=dropout,
        )

    return ScalableTransformerPolicy(
        in_nodes=in_nodes,
        embed_dim=192,
        nhead=6,
        num_layers=3,
        dropout=dropout,
    )


